function parsed = parseSerializationStream(streamBytes, fileInfo, options)
%PARSESERIALIZATIONSTREAM Parse one lower-level R serialization stream.

% Copyright 2026 The MathWorks, Inc.

reader = rdata.internal.SerializationReader(streamBytes, fileInfo.SerializationFormat);
context = struct( ...
    Options=options, ...
    FileInfo=fileInfo, ...
    Depth=0, ...
    State=rdata.internal.ParseState());
robj = rdata.internal.parseSexp(reader, context);
if reader.Position <= numel(streamBytes)
    error("rdata:InvalidHeader", ...
        "R serialization stream contains trailing bytes after the top-level object.")
end

parsed = struct( ...
    Object=robj, ...
    FileInfo=fileInfo);
end
