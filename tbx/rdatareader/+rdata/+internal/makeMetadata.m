function metadata = makeMetadata(robj, fileInfo, objectName)
%MAKEMETADATA Create public metadata for one parsed R object.

% Copyright 2026 The MathWorks, Inc.

metadata = struct( ...
    Filename=getFieldOrDefault(fileInfo, "Filename", ""), ...
    FileType=getFieldOrDefault(fileInfo, "FileType", ""), ...
    Compression=getFieldOrDefault(fileInfo, "Compression", ""), ...
    SerializationFormat=getFieldOrDefault(fileInfo, "SerializationFormat", ""), ...
    SerializationVersion=getFieldOrDefault(fileInfo, "SerializationVersion", NaN), ...
    WriterVersion=getFieldOrDefault(fileInfo, "WriterVersion", ""), ...
    MinReaderVersion=getFieldOrDefault(fileInfo, "MinReaderVersion", ""), ...
    NativeEncoding=getFieldOrDefault(fileInfo, "NativeEncoding", ""), ...
    ObjectName=string(objectName), ...
    RType=robj.Type, ...
    RClass=robj.RClass, ...
    Names=robj.Names, ...
    Dimensions=robj.Dimensions, ...
    Encoding=robj.Encoding, ...
    RawBytes={robj.RawBytes}, ...
    Missing=robj.Missing, ...
    IsReference=robj.IsReference, ...
    ReferenceIndex=robj.ReferenceIndex, ...
    Attributes=attributeSummary(robj.Attributes));
end

function value = getFieldOrDefault(s, fieldName, defaultValue)
if isstruct(s) && isfield(s, fieldName)
    value = s.(fieldName);
else
    value = defaultValue;
end
end

function summary = attributeSummary(attributes)
names = strings(numel(attributes), 1);
types = strings(numel(attributes), 1);
for k = 1:numel(attributes)
    names(k) = attributes(k).Name;
    types(k) = attributes(k).Value.Type;
end
summary = table(names, types, VariableNames=["Name", "RType"]);
end
