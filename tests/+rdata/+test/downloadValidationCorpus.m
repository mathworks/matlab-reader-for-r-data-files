function manifestFile = downloadValidationCorpus(options)
%DOWNLOADVALIDATIONCORPUS Download optional real-world test fixtures.
%   MANIFESTFILE = DOWNLOADVALIDATIONCORPUS downloads the external corpus
%   needed by the non-slow corpus tests into tests/testdata/corpus and
%   writes a local manifest with absolute root metadata.
%
%   DOWNLOADVALIDATIONCORPUS(IncludeSlow=true) also downloads the large
%   Zenodo fixture used by the slow smoke test.
%
%   DOWNLOADVALIDATIONCORPUS(OutputFolder=FOLDER) downloads to another
%   folder. The folder should contain the manifest.json file used by
%   realWorldCorpusTest.
%
%   DOWNLOADVALIDATIONCORPUS(VerifyOnly=true) verifies an existing corpus
%   without downloading missing files.

% Copyright 2026 The MathWorks, Inc.

arguments
    options.OutputFolder (1,1) string = string(fullfile(currentProject().RootFolder, "tests", "testdata", "corpus"));
    options.IncludeSlow (1,1) logical = false
    options.Force (1,1) logical = false
    options.VerifyOnly (1,1) logical = false
end

entries = validationCorpusCatalog();
if options.IncludeSlow
    entries = entries([entries.IncludeInFast] | [entries.IncludeInSlow]);
else
    entries = entries([entries.IncludeInFast]);
end

if ~isfolder(options.OutputFolder)
    if options.VerifyOnly
        error("rdata:MissingCorpusFolder", ...
            "Corpus folder does not exist: %s.", options.OutputFolder)
    end
    mkdir(options.OutputFolder)
end

archiveCache = configureDictionary("string", "string");
try
    fprintf("Preparing validation corpus in %s\n", options.OutputFolder)
    for k = 1:numel(entries)
        specs = [entries(k).RSerializedFiles entries(k).ComparisonFiles];
        for j = 1:numel(specs)
            archiveCache = prepareCorpusFile(specs(j), options.OutputFolder, options, archiveCache);
        end
    end

    manifestFile = fullfile(options.OutputFolder, "manifest.json");
    if ~options.VerifyOnly
        manifest = makeManifest(entries, options.OutputFolder);
        writeTextFile(manifestFile, encodeJson(manifest));
    end
catch exception
    removeArchiveCache(archiveCache)
    rethrow(exception)
end

removeArchiveCache(archiveCache)
fprintf("Validation corpus ready: %s\n", manifestFile)
end

function archiveCache = prepareCorpusFile(spec, outputFolder, options, archiveCache)
targetFile = fullfile(outputFolder, spec.RelativePath);
if isfile(targetFile) && ~options.Force
    verifyCorpusFile(targetFile, spec)
    fprintf("Verified %s\n", spec.RelativePath)
    return
end

if options.VerifyOnly
    error("rdata:MissingCorpusFile", ...
        "Corpus file is missing: %s.", targetFile)
end

targetFolder = fileparts(targetFile);
if ~isfolder(targetFolder)
    mkdir(targetFolder)
end

if strlength(spec.ArchivePath) == 0
    downloadDirectFile(spec.SourceUrl, targetFile)
else
    archiveCache = copyArchiveMember(spec, targetFile, archiveCache);
end

verifyCorpusFile(targetFile, spec)
fprintf("Downloaded %s\n", spec.RelativePath)
end

function downloadDirectFile(sourceUrl, targetFile)
temporaryFile = string(tempname(fileparts(targetFile)));
cleanup = onCleanup(@() deleteIfFile(temporaryFile));

try
    savedFile = websave(temporaryFile, sourceUrl, weboptions(Timeout=120));
catch exception
    error("rdata:DownloadFailed", ...
        "Unable to download %s: %s.", sourceUrl, exception.message)
end

movefile(savedFile, targetFile, "f")
end

function archiveCache = copyArchiveMember(spec, targetFile, archiveCache)
[archiveFolder, archiveCache] = getArchiveFolder(spec.SourceUrl, archiveCache);
sourceFile = fullfile(archiveFolder, replace(spec.ArchivePath, "/", filesep));
if ~isfile(sourceFile)
    error("rdata:ArchiveMemberMissing", ...
        "Downloaded archive does not contain expected member: %s.", spec.ArchivePath)
end
copyfile(sourceFile, targetFile, "f")
end

function [archiveFolder, archiveCache] = getArchiveFolder(sourceUrl, archiveCache)
cacheKey = sourceUrl;
if isKey(archiveCache, cacheKey)
    archiveFolder = archiveCache(cacheKey);
    return
end

archiveFile = string(tempname) + ".tar.gz";
archiveCleanup = onCleanup(@() deleteIfFile(archiveFile));

try
    savedArchive = websave(archiveFile, sourceUrl, weboptions(Timeout=120));
catch exception
    error("rdata:DownloadFailed", ...
        "Unable to download %s: %s.", sourceUrl, exception.message)
end

archiveFolder = string(tempname);
mkdir(archiveFolder)
try
    untar(savedArchive, archiveFolder);
catch exception
    removeFolder(archiveFolder)
    error("rdata:ArchiveExtractFailed", ...
        "Unable to extract %s: %s.", sourceUrl, exception.message)
end

archiveCache(cacheKey) = archiveFolder;
delete(archiveCleanup)
end

function verifyCorpusFile(filename, spec)
fileInfo = dir(filename);
if isempty(fileInfo)
    error("rdata:MissingCorpusFile", "Corpus file is missing: %s.", filename)
end

if fileInfo.bytes ~= spec.Bytes
    error("rdata:CorpusSizeMismatch", ...
        "Expected %s to contain %d bytes, but found %d.", ...
        filename, spec.Bytes, fileInfo.bytes)
end

actualHash = sha256File(filename);
if actualHash ~= lower(spec.Sha256)
    error("rdata:CorpusHashMismatch", ...
        "SHA-256 mismatch for %s. Expected %s but found %s.", ...
        filename, spec.Sha256, actualHash)
end
end

function manifest = makeManifest(entries, outputFolder)
manifest = struct( ...
    created=char(datetime("today", Format="yyyy-MM-dd")), ...
    copyright="Copyright 2026 The MathWorks, Inc.", ...
    root=char(outputFolder), ...
    description="Validation corpus downloaded from public source URLs for MATLAB Reader for R Data Files tests.", ...
    caveats=["The corpus is downloaded on demand and is not vendored with the repository."; ...
        "Comparison files validate common values and dimensions but do not preserve all R-specific metadata."], ...
    fixtures=makeManifestFixtures(entries));
end

function fixtures = makeManifestFixtures(entries)
fixtures = repmat(struct( ...
    id="", source="", dataset="", purpose="", ...
    r_serialized_files=struct([]), comparison_files=struct([]), source_urls=strings(0, 1)), ...
    numel(entries), 1);

for k = 1:numel(entries)
    fixtures(k).id = entries(k).Id;
    fixtures(k).source = entries(k).Source;
    fixtures(k).dataset = entries(k).Dataset;
    fixtures(k).purpose = entries(k).Purpose;
    fixtures(k).r_serialized_files = manifestFileSpecs(entries(k).RSerializedFiles);
    fixtures(k).comparison_files = manifestFileSpecs(entries(k).ComparisonFiles);
    fixtures(k).source_urls = unique([entries(k).RSerializedFiles.SourceUrl entries(k).ComparisonFiles.SourceUrl], "stable");
end
end

function manifestSpecs = manifestFileSpecs(specs)
manifestSpecs = repmat(struct(relative_path="", bytes=0, sha256=""), numel(specs), 1);
for k = 1:numel(specs)
    manifestSpecs(k).relative_path = specs(k).RelativePath;
    manifestSpecs(k).bytes = specs(k).Bytes;
    manifestSpecs(k).sha256 = specs(k).Sha256;
end
end

function text = encodeJson(value)
try
    text = jsonencode(value, PrettyPrint=true);
catch
    text = jsonencode(value);
end
end

function writeTextFile(filename, text)
fileId = fopen(filename, "w", "n", "UTF-8");
if fileId < 0
    error("rdata:FileOpenError", "Unable to write file: %s.", filename)
end
cleanup = onCleanup(@() fclose(fileId));
fwrite(fileId, char(text), "char");
end

function hashText = sha256File(filename)
fileId = fopen(filename, "rb");
if fileId < 0
    error("rdata:FileOpenError", "Unable to open file: %s.", filename)
end
cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId, Inf, "*uint8").';
hashText = sha256Bytes(bytes);
end

function hashText = sha256Bytes(message)
k = uint32([
    1116352408 1899447441 3049323471 3921009573 961987163 1508970993 2453635748 2870763221 ...
    3624381080 310598401 607225278 1426881987 1925078388 2162078206 2614888103 3248222580 ...
    3835390401 4022224774 264347078 604807628 770255983 1249150122 1555081692 1996064986 ...
    2554220882 2821834349 2952996808 3210313671 3336571891 3584528711 113926993 338241895 ...
    666307205 773529912 1294757372 1396182291 1695183700 1986661051 2177026350 2456956037 ...
    2730485921 2820302411 3259730800 3345764771 3516065817 3600352804 4094571909 275423344 ...
    430227734 506948616 659060556 883997877 958139571 1322822218 1537002063 1747873779 ...
    1955562222 2024104815 2227730452 2361852424 2428436474 2756734187 3204031479 3329325298]);
h = uint32([
    1779033703 3144134277 1013904242 2773480762 ...
    1359893119 2600822924 528734635 1541459225]);

message = uint8(message(:).');
bitLength = uint64(numel(message))*uint64(8);
message = [message uint8(128)];
padLength = mod(56 - mod(numel(message), 64), 64);
message = [message zeros(1, padLength, "uint8") encodeUint64BigEndian(bitLength)];

for blockStart = 1:64:numel(message)
    block = message(blockStart:blockStart + 63);
    w = zeros(1, 64, "uint32");
    for t = 1:16
        first = 4*(t - 1) + 1;
        w(t) = bytesToBigEndianUInt32(block(first:first + 3));
    end
    for t = 17:64
        s0 = bitxor(bitxor(rotr(w(t - 15), 7), rotr(w(t - 15), 18)), bitshift(w(t - 15), -3));
        s1 = bitxor(bitxor(rotr(w(t - 2), 17), rotr(w(t - 2), 19)), bitshift(w(t - 2), -10));
        w(t) = add32(w(t - 16), s0, w(t - 7), s1);
    end

    a = h(1); b = h(2); c = h(3); d = h(4);
    e = h(5); f = h(6); g = h(7); hh = h(8);
    for t = 1:64
        s1 = bitxor(bitxor(rotr(e, 6), rotr(e, 11)), rotr(e, 25));
        ch = bitxor(bitand(e, f), bitand(bitcmp(e, "uint32"), g));
        temp1 = add32(hh, s1, ch, k(t), w(t));
        s0 = bitxor(bitxor(rotr(a, 2), rotr(a, 13)), rotr(a, 22));
        maj = bitxor(bitxor(bitand(a, b), bitand(a, c)), bitand(b, c));
        temp2 = add32(s0, maj);
        hh = g;
        g = f;
        f = e;
        e = add32(d, temp1);
        d = c;
        c = b;
        b = a;
        a = add32(temp1, temp2);
    end

    h = [
        add32(h(1), a) add32(h(2), b) add32(h(3), c) add32(h(4), d) ...
        add32(h(5), e) add32(h(6), f) add32(h(7), g) add32(h(8), hh)];
end

hashText = lower(join(string(arrayfun(@(x) sprintf("%08x", x), h)), ""));
end

function value = add32(varargin)
sumValue = uint64(0);
modulus = uint64(4294967296);
for k = 1:nargin
    sumValue = mod(sumValue + uint64(varargin{k}), modulus);
end
value = uint32(sumValue);
end

function value = rotr(value, n)
value = bitor(bitshift(value, -n), bitshift(value, 32 - n));
end

function value = bytesToBigEndianUInt32(bytes)
bytes = uint32(bytes);
value = bitor( ...
    bitor(bitshift(bytes(1), 24), bitshift(bytes(2), 16)), ...
    bitor(bitshift(bytes(3), 8), bytes(4)));
end

function bytes = encodeUint64BigEndian(value)
bytes = zeros(1, 8, "uint8");
for k = 8:-1:1
    bytes(k) = uint8(bitand(value, uint64(255)));
    value = bitshift(value, -8);
end
end

