spec = struct( ...
    RelativePath=relativePath, ...
    Bytes=bytes, ...
    Sha256=sha256, ...
    SourceUrl=sourceUrl, ...
    ArchivePath=archivePath);
end

function specs = emptyFileSpecs()
specs = repmat(fileSpec("", 0, "", ""), 0, 1);
end

function removeArchiveCache(archiveCache)
cacheKeys = keys(archiveCache);
for k = 1:numel(cacheKeys)
    removeFolder(archiveCache(cacheKeys(k)))
end
end

function removeFolder(folder)
if isfolder(folder)
    rmdir(folder, "s")
end
end

function deleteIfFile(filename)
if isfile(filename)
    delete(filename)
end
end
